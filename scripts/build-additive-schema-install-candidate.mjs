/**
 * REDDIRT-PRODUCTION-ADDITIVE-SCHEMA-INSTALL-PLAN-1.0 — Phase 2
 * Parses data/sql/unsafe-production-to-current-schema-diff.sql + data/production-db-baseline-audit.json
 * to emit a curated additive-only candidate. No database I/O.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SLICE = "REDDIRT-PRODUCTION-ADDITIVE-SCHEMA-INSTALL-PLAN-1.0";
const SOURCE_DIFF = path.join(ROOT, "data/sql/unsafe-production-to-current-schema-diff.sql");
const AUDIT_PATH = path.join(ROOT, "data/production-db-baseline-audit.json");
const ALLOWLIST_PATH = path.join(ROOT, "data/additive-schema-manual-allowlists.json");
const OUT_SQL = path.join(ROOT, "data/sql/additive-schema-install-candidate.sql");
const OUT_REJECT = path.join(ROOT, "data/sql/additive-schema-install-rejected-statements.sql");
const OUT_NOTES = path.join(ROOT, "data/sql/additive-schema-install-review-notes.sql");
const OUT_PLAN_JSON = path.join(ROOT, "data/additive-schema-install-plan.json");
const OUT_PLAN_MD = path.join(ROOT, "docs/additive-schema-install-plan.md");

const SQL_HEADER = `-- REDDIRT-PRODUCTION-ADDITIVE-SCHEMA-INSTALL-PLAN-1.0
-- CANDIDATE ONLY.
-- DO NOT RUN ON PRODUCTION.
-- Clone/shadow proof required before any execution packet.
-- This file is generated by scripts/build-additive-schema-install-candidate.mjs.
`;

const EXPLICIT_HIGH_RISK = new Set(
  [
    "voterrecord",
    "voterinteraction",
    "votersignal",
    "votervoteplan",
    "votersnapshotchange",
    "voterfilesnapshot",
    "votermodelclassification",
    "countyvotermetrics",
  ]
);

const SEMANTIC_TOUCH_DENY = [
  "people",
  "person_profiles",
  "contacts",
  "events",
  "event_requests",
  "counties",
  "media_assets",
  "submissions",
  "message_audiences",
  "message_events",
  "path_to_victory",
];

const COLLISION_NAMES = ["ar02_voters", "voters", "voter_registry", "voter_profiles", "voter_scores", "voter_vote_history"];

/** Prisma PascalCase / mixed refs in diff → likely physical public.table in audit (snake). */
const REF_TO_AUDIT_TABLE = new Map(
  Object.entries({
    user: "users",
    submission: "submissions",
    county: "counties",
    event: "events",
    contact: "contacts",
    person: "people",
    profile: "profiles",
  })
);

function splitSqlStatements(sql) {
  const out = [];
  let cur = "";
  let i = 0;
  let inSq = false;
  let inDq = false;
  let bcom = 0;
  while (i < sql.length) {
    const c = sql[i];
    const n = sql[i + 1];
    if (bcom > 0) {
      if (c === "/" && n === "*") {
        cur += "/*";
        i += 2;
        bcom++;
        continue;
      }
      if (c === "*" && n === "/") {
        cur += "*/";
        i += 2;
        bcom--;
        continue;
      }
      cur += c;
      i++;
      continue;
    }
    if (!inSq && !inDq) {
      if (c === "-" && n === "-") {
        while (i < sql.length && sql[i] !== "\n") {
          cur += sql[i];
          i++;
        }
        if (i < sql.length) {
          cur += sql[i];
          i++;
        }
        continue;
      }
      if (c === "/" && n === "*") {
        cur += "/*";
        i += 2;
        bcom++;
        continue;
      }
    }
    if (!inDq && c === "'") {
      if (inSq && n === "'") {
        cur += "''";
        i += 2;
        continue;
      }
      inSq = !inSq;
      cur += c;
      i++;
      continue;
    }
    if (inSq) {
      cur += c;
      i++;
      continue;
    }
    if (!inSq && c === '"') {
      if (inDq && n === '"') {
        cur += '""';
        i += 2;
        continue;
      }
      inDq = !inDq;
      cur += c;
      i++;
      continue;
    }
    if (!inSq && !inDq && c === ";") {
      const t = cur.trim();
      if (t) out.push(t);
      cur = "";
      i++;
      continue;
    }
    cur += c;
    i++;
  }
  const t = cur.trim();
  if (t) out.push(t);
  return out;
}

function stripLeadingLineComments(stmt) {
  return stmt.replace(/^(\s*--[^\n]*\n)+/g, "").trim();
}

function toSnakeCase(str) {
  return str
    .replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/-/g, "_")
    .toLowerCase();
}

function loadAllowlists() {
  if (!fs.existsSync(ALLOWLIST_PATH)) {
    return { fkLegacyTargets: [], highRiskVoterTables: [] };
  }
  try {
    const j = JSON.parse(fs.readFileSync(ALLOWLIST_PATH, "utf8"));
    return {
      fkLegacyTargets: Array.isArray(j.fkLegacyTargets) ? j.fkLegacyTargets : [],
      highRiskVoterTables: Array.isArray(j.highRiskVoterTables) ? j.highRiskVoterTables : [],
    };
  } catch {
    return { fkLegacyTargets: [], highRiskVoterTables: [] };
  }
}

function buildExistingPublicSet(tables) {
  const s = new Set();
  for (const t of tables) {
    const low = String(t).toLowerCase();
    if (!low.startsWith("public.")) continue;
    const tab = low.slice("public.".length);
    s.add(tab);
  }
  return s;
}

function buildEnumSet(enums) {
  const s = new Set();
  for (const e of enums || []) {
    const low = String(e).toLowerCase();
    s.add(low);
    if (low.includes(".")) s.add(low.split(".").pop());
  }
  return s;
}

function touchesProvider(stmt) {
  return /"auth"\./i.test(stmt) || /"storage"\./i.test(stmt) || /"realtime"\./i.test(stmt) || /"vault"\./i.test(stmt);
}

function hasForbiddenTokens(stmt) {
  if (/\bDROP\b/i.test(stmt)) return "contains_drop";
  if (/\bTRUNCATE\b/i.test(stmt)) return "truncate";
  if (/\bDELETE\s+FROM\b/i.test(stmt)) return "delete";
  if (/\bINSERT\s+INTO\b/i.test(stmt)) return "insert";
  if (/\bUPDATE\s+/i.test(stmt) && !/UPDATE\s+STATISTICS/i.test(stmt)) return "update";
  if (/ALTER\s+TABLE[\s\S]*\bDROP\b/i.test(stmt)) return "alter_drop";
  return "";
}

function extractCreateTypeName(body) {
  const m = body.match(/^\s*CREATE\s+TYPE\s+(?:(?:"public")\.)?"([^"]+)"\s+AS\s+ENUM/i);
  return m ? m[1] : null;
}

function extractCreateTableName(body) {
  const m = body.match(/^\s*CREATE\s+TABLE\s+(?:(?:"public")\.)?"([^"]+)"\s*\(/i);
  return m ? m[1] : null;
}

function extractAlterTableName(body) {
  const m = body.match(/^\s*ALTER\s+TABLE\s+(?:(?:"public")\.)?"([^"]+)"/i);
  return m ? m[1] : null;
}

function extractIndexOnTable(body) {
  const m = body.match(/\bON\s+(?:(?:"public")\.)?"([^"]+)"/i);
  return m ? m[1] : null;
}

function extractReferencesTargets(body) {
  const out = [];
  const re = /\bREFERENCES\s+(?:(?:"public")\.)?"([^"]+)"\s*\(/gi;
  let m;
  while ((m = re.exec(body)) !== null) out.push(m[1]);
  return out;
}

function isHighRiskVoterTable(name, allowVoter) {
  const low = name.toLowerCase();
  if (allowVoter.has(low)) return false;
  if (EXPLICIT_HIGH_RISK.has(low)) return true;
  if (low.startsWith("voter")) return true;
  if (low.includes("voter")) return true;
  for (const c of COLLISION_NAMES) {
    if (low === c || low.includes(c)) return true;
  }
  return false;
}

function touchesSemanticDeny(body) {
  const low = body.toLowerCase();
  for (const d of SEMANTIC_TOUCH_DENY) {
    if (low.includes(`"public"."${d}"`)) return true;
  }
  return false;
}

function fkWhitelisted(fromTable, toTable, fkLegacyTargets) {
  const f = fromTable.toLowerCase();
  const t = toTable.toLowerCase();
  return fkLegacyTargets.some(
    (x) => String(x.from || "").toLowerCase() === f && String(x.to || "").toLowerCase() === t
  );
}

/** Resolve diff quoted identifier to audit public.table names (snake). */
function auditCandidatesForRef(refName) {
  const raw = refName;
  const c = new Set();
  c.add(raw.toLowerCase());
  c.add(toSnakeCase(raw));
  const mapped = REF_TO_AUDIT_TABLE.get(raw.toLowerCase());
  if (mapped) c.add(mapped);
  return [...c];
}

function refHitsExistingPublic(refName, existingPublic) {
  return auditCandidatesForRef(refName).some((x) => existingPublic.has(x));
}

function main() {
  const allow = loadAllowlists();
  const allowVoter = new Set(allow.highRiskVoterTables.map((x) => String(x).toLowerCase()));

  let sourceDiffReadable = false;
  let diffSql = "";
  if (fs.existsSync(SOURCE_DIFF)) {
    sourceDiffReadable = true;
    diffSql = fs.readFileSync(SOURCE_DIFF, "utf8");
  }

  if (!fs.existsSync(AUDIT_PATH)) {
    console.error("FAIL: missing data/production-db-baseline-audit.json");
    process.exit(1);
  }

  const audit = JSON.parse(fs.readFileSync(AUDIT_PATH, "utf8"));
  const observedTables = audit?.observed?.tables || [];
  const observedEnums = audit?.observed?.enums || [];
  const existingPublic = buildExistingPublicSet(observedTables);
  const existingEnumNames = buildEnumSet(observedEnums);

  const statements = sourceDiffReadable ? splitSqlStatements(diffSql) : [];

  const included = [];
  const rejected = [];
  const reasonCounts = new Map();
  const bump = (r) => reasonCounts.set(r, (reasonCounts.get(r) || 0) + 1);

  const dispatch = (stmt, body, rejectReason) => {
    if (rejectReason) {
      rejected.push({ reason: rejectReason, sql: stmt });
      bump(rejectReason);
    } else {
      included.push(stmt);
    }
  };

  const candidateNewTables = new Set();

  for (const stmt of statements) {
    const body = stripLeadingLineComments(stmt);
    if (!body) continue;

    const forbid = hasForbiddenTokens(body);
    if (forbid) {
      dispatch(stmt, body, forbid);
      continue;
    }
    if (touchesProvider(body)) {
      dispatch(stmt, body, "provider_schema_touch");
      continue;
    }

    if (/^\s*CREATE\s+TYPE/i.test(body)) {
      const tn = extractCreateTypeName(body);
      if (!tn) {
        dispatch(stmt, body, "create_type_shape_unrecognized");
        continue;
      }
      const tnl = tn.toLowerCase();
      if (existingEnumNames.has(`public.${tnl}`) || existingEnumNames.has(tnl)) {
        dispatch(stmt, body, "create_type_already_observed");
        continue;
      }
      dispatch(stmt, body, null);
      continue;
    }

    if (/^\s*CREATE\s+TABLE/i.test(body)) {
      const tn = extractCreateTableName(body);
      if (!tn) {
        dispatch(stmt, body, "create_table_shape_unrecognized");
        continue;
      }
      if (refHitsExistingPublic(tn, existingPublic)) {
        dispatch(stmt, body, "create_table_target_already_observed");
        continue;
      }
      if (isHighRiskVoterTable(tn, allowVoter)) {
        dispatch(stmt, body, "high_risk_voter_semantic_table");
        continue;
      }
      dispatch(stmt, body, null);
      candidateNewTables.add(tn.toLowerCase());
      continue;
    }

    if (/^\s*CREATE\s+(UNIQUE\s+)?INDEX/i.test(body)) {
      const onT = extractIndexOnTable(body);
      if (!onT) {
        dispatch(stmt, body, "create_index_on_unparsed");
        continue;
      }
      const onL = onT.toLowerCase();
      if (!candidateNewTables.has(onL)) {
        dispatch(stmt, body, "create_index_on_table_not_in_candidate_new_set");
        continue;
      }
      if (existingPublic.has(onL) || refHitsExistingPublic(onT, existingPublic)) {
        dispatch(stmt, body, "create_index_on_existing_public_table");
        continue;
      }
      dispatch(stmt, body, null);
      continue;
    }

    if (/^\s*ALTER\s+TABLE/i.test(body)) {
      const at = extractAlterTableName(body);
      if (!at) {
        dispatch(stmt, body, "alter_table_unparsed");
        continue;
      }
      const atl = at.toLowerCase();
      if (!candidateNewTables.has(atl)) {
        dispatch(stmt, body, "alter_table_not_new_candidate_table");
        continue;
      }
      if (!/^\s*ALTER\s+TABLE[\s\S]+\b(ADD\s+CONSTRAINT|ADD\s+FOREIGN\s+KEY)\b/i.test(body)) {
        dispatch(stmt, body, "alter_table_not_add_constraint_or_fk");
        continue;
      }
      let fkReject = null;
      for (const r of extractReferencesTargets(body)) {
        if (refHitsExistingPublic(r, existingPublic) && !fkWhitelisted(at, r, allow.fkLegacyTargets)) {
          fkReject = "fk_to_legacy_public_without_whitelist";
          break;
        }
        if (isHighRiskVoterTable(r, allowVoter)) {
          fkReject = "fk_to_high_risk_voter_table";
          break;
        }
      }
      if (fkReject) {
        dispatch(stmt, body, fkReject);
        continue;
      }
      if (touchesSemanticDeny(body)) {
        dispatch(stmt, body, "semantic_legacy_touch_in_alter");
        continue;
      }
      dispatch(stmt, body, null);
      continue;
    }

    dispatch(stmt, body, "statement_class_not_included");
  }

  let createTypeIncluded = 0;
  let createTableIncluded = 0;
  let createIndexIncluded = 0;
  let alterTableIncluded = 0;
  for (const s of included) {
    const b = stripLeadingLineComments(s);
    if (/^\s*CREATE\s+TYPE/i.test(b)) createTypeIncluded++;
    else if (/^\s*CREATE\s+TABLE/i.test(b)) createTableIncluded++;
    else if (/^\s*CREATE\s+(UNIQUE\s+)?INDEX/i.test(b)) createIndexIncluded++;
    else if (/^\s*ALTER\s+TABLE/i.test(b)) alterTableIncluded++;
  }

  const includedTables = [...candidateNewTables].sort();
  const rejectionReasons = [...reasonCounts.entries()]
    .map(([reason, count]) => ({ reason, count }))
    .sort((a, b) => b.count - a.count);

  fs.mkdirSync(path.dirname(OUT_SQL), { recursive: true });
  const bodySql = included.map((s) => stripLeadingLineComments(s)).join(";\n\n");
  fs.writeFileSync(OUT_SQL, `${SQL_HEADER}\n${bodySql}${included.length ? ";\n" : ""}`, "utf8");

  const rejLines = rejected.map((r) => {
    const c = r.sql
      .split("\n")
      .map((line) => (line.trim() ? `-- ${line}` : "--"))
      .join("\n");
    return `-- reason=${r.reason}\n${c}`;
  });
  fs.writeFileSync(
    OUT_REJECT,
    `-- Rejected statements from unsafe diff filter (${rejected.length})\n-- Source: ${path.relative(ROOT, SOURCE_DIFF)}\n\n${rejLines.join("\n\n")}\n`,
    "utf8"
  );

  const notes = `${SQL_HEADER}
-- Operator review notes (generated ${new Date().toISOString()})
-- The raw Prisma diff is not safe to execute.
-- Included statements: ${included.length}; rejected: ${rejected.length}.
-- Audit public tables observed: ${[...existingPublic].length}.
-- Optional allowlists: ${path.relative(ROOT, ALLOWLIST_PATH)}
`;
  fs.writeFileSync(OUT_NOTES, notes, "utf8");

  const plan = {
    schemaVersion: "1.0",
    slice: SLICE,
    generatedAt: new Date().toISOString(),
    mode: "curated_additive_candidate",
    sourceDiff: path.relative(ROOT, SOURCE_DIFF),
    candidateSql: path.relative(ROOT, OUT_SQL),
    rejectedSql: path.relative(ROOT, OUT_REJECT),
    summary: {
      candidateStatementCount: included.length,
      rejectedStatementCount: rejected.length,
      createTypeIncluded,
      createTableIncluded,
      createIndexIncluded,
      alterTableIncluded,
      destructiveStatementsIncluded: 0,
      providerSchemaStatementsIncluded: 0,
      legacyExistingTableStatementsIncluded: 0,
      highRiskVoterStatementsIncluded: 0,
    },
    includedTables,
    excludedTables: [],
    rejectionReasons,
    requiresCloneProof: true,
    safeForProduction: false,
    nextRecommendedSlice: "REDDIRT-ADDITIVE-SCHEMA-CLONE-PROOF-1.0",
    meta: {
      sourceDiffReadable,
      auditPath: path.relative(ROOT, AUDIT_PATH),
      allowlistPath: path.relative(ROOT, ALLOWLIST_PATH),
      observedPublicTableCount: existingPublic.size,
    },
  };

  fs.writeFileSync(OUT_PLAN_JSON, JSON.stringify(plan, null, 2), "utf8");

  const md = `# Additive schema install plan

**Slice:** \`${SLICE}\`  
**Generated:** ${plan.generatedAt}

## Critical safety statement

**The raw Prisma diff is not safe to execute.** It can drop provider constraints, mutate legacy warehouse tables, and destroy production relationships. This plan derives a **strictly additive** candidate subset from that diff plus \`production-db-baseline-audit.json\`. **Do not run** the raw diff. **Do not run** the candidate on production until clone proof and Steve-governed execution.

## Artifacts

| Artifact | Path |
|----------|------|
| Unsafe diff (input) | [\`data/sql/unsafe-production-to-current-schema-diff.sql\`](../data/sql/unsafe-production-to-current-schema-diff.sql) |
| Candidate SQL | [\`data/sql/additive-schema-install-candidate.sql\`](../data/sql/additive-schema-install-candidate.sql) |
| Rejected SQL | [\`data/sql/additive-schema-install-rejected-statements.sql\`](../data/sql/additive-schema-install-rejected-statements.sql) |
| Review notes | [\`data/sql/additive-schema-install-review-notes.sql\`](../data/sql/additive-schema-install-review-notes.sql) |
| Plan JSON | [\`data/additive-schema-install-plan.json\`](../data/additive-schema-install-plan.json) |
| Manual allowlists (optional) | [\`data/additive-schema-manual-allowlists.json\`](../data/additive-schema-manual-allowlists.json) |
| Unsafe analysis | [\`docs/unsafe-production-schema-diff-analysis.md\`](./unsafe-production-schema-diff-analysis.md) · [\`data/unsafe-production-schema-diff-analysis.json\`](../data/unsafe-production-schema-diff-analysis.json) |

## Summary

| Metric | Value |
|--------|------:|
| Candidate statements | ${plan.summary.candidateStatementCount} |
| Rejected statements | ${plan.summary.rejectedStatementCount} |
| CREATE TYPE / TABLE / INDEX / ALTER (included) | ${createTypeIncluded} / ${createTableIncluded} / ${createIndexIncluded} / ${alterTableIncluded} |
| \`requiresCloneProof\` | **true** |
| \`safeForProduction\` | **false** |
| Next slice | \`${plan.nextRecommendedSlice}\` |

## Top rejection reasons

${rejectionReasons.slice(0, 30).map((x) => `- **${x.reason}:** ${x.count}`).join("\n") || "- (none)"}
`;

  fs.writeFileSync(OUT_PLAN_MD, md, "utf8");

  console.log(sourceDiffReadable ? "OK build-additive-schema-install-candidate.mjs" : "WARN build-additive-schema-install-candidate.mjs (missing unsafe diff)");
  console.log(" ", path.relative(ROOT, OUT_SQL), `included=${included.length} rejected=${rejected.length}`);
}

main();

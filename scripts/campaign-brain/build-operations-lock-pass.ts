/**
 * Operations Lock Pass — Campaign Operations Mode.
 * Converts systems into weekly human action lists. NOT calendar operational lock.
 * NOT Google Calendar. NOT /events publish.
 *
 * Usage: npm run campaign-brain:operations-lock:build
 */

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { BRAIN_DATA, BRAIN_ROOT, readJson } from "./lib/inputs";

const OPS_OUT = path.join(BRAIN_ROOT, "operations");
const PACKETS_OUT = path.join(OPS_OUT, "weekly-packets");
const SHERWOOD_OUT = path.join(OPS_OUT, "sherwood-60");
const OPS_DATA = path.join(BRAIN_DATA, "operations");
const TWENTY_WEEK = path.join(process.cwd(), "data/election-plan/twenty-week-plan.json");

const DISCLAIMER =
  "Campaign Operations Mode. Weekly action lists for named owners. Calendar Phase C sign-off still required before calendar operational lock. Not Kelly's final Google Calendar.";

const LABOR_DAY = "2026-09-07";

type OwnershipRow = {
  id: string;
  function: string;
  owner: string;
  backup: string;
  status: string;
  nextAction: string;
  dueDate: string;
  weeklyDeliverable: string;
};

type WeekPlan = {
  weekNumber: number;
  range: string;
  status: string;
  cluster: string;
  clusterFocus?: string;
  cities: string[];
  counties?: string[];
  focus: string;
  events?: string[];
  volunteerGoals?: string[];
  coalitionGoals?: string[];
  storytellingGoals?: string[];
  endorsementGoals?: string[];
  gotvGoals?: string[];
  metrics?: Array<{ label: string; target: number | string }>;
};

type EndorsementTarget = {
  id: string;
  organization: string;
  tier: number;
  owner: string;
  askDate: string;
  status: string;
  nextAction: string;
};

function ensureDir(p: string) {
  mkdirSync(p, { recursive: true });
}

function padWeek(n: number) {
  return `week-${String(n).padStart(2, "0")}`;
}

function bulletList(items: string[] | undefined, fallback = "- _None assigned_") {
  if (!items?.length) return fallback;
  return items.map((i) => `- ${i}`).join("\n");
}

function metricsTable(metrics: WeekPlan["metrics"]) {
  if (!metrics?.length) return "_No metrics defined._";
  return `| Metric | Target |\n|--------|--------|\n${metrics.map((m) => `| ${m.label} | ${m.target} |`).join("\n")}`;
}


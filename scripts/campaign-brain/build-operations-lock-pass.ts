function buildOwnershipDashboard(assignments: OwnershipRow[], generatedAt: string): string {
  const unassigned = assignments.filter((a) => {
    const o = a.owner.trim().toLowerCase();
    return !o || o === "unassigned" || o === "tbd" || o.startsWith("tbd");
  }).length;
  return `# Ownership Dashboard

> ${DISCLAIMER}

**Generated:** ${generatedAt.slice(0, 10)}

| Status | Count |
|--------|------:|
| Functions defined | ${assignments.length} |
| **Unassigned — assign before lunch** | **${unassigned}** |
| Critical path | ${assignments.filter((a) => a.status === "critical").length} |

## Assignments

| Function | Owner | Backup | Status | Next action | Due |
|----------|-------|--------|--------|-------------|-----|
${assignments.map((a) => `| ${a.function} | **${a.owner}** | ${a.backup || "—"} | ${a.status} | ${a.nextAction} | ${a.dueDate} |`).join("\n")}

## Rule

No shared ownership. No committees. **One name beside every box.**

Edit \`data/campaign-brain/operations/ownership-registry.source.json\` and re-run \`npm run campaign-brain:operations-lock:build\`.
`;
}


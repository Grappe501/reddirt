function buildCoalitionSprint() {
  const categories = [
    { id: "naacp", label: "NAACP branches", goal: 20, owner: "NAACP Program" },
    { id: "labor", label: "Labor halls / union leadership", goal: 15, owner: "Labor Program" },
    { id: "educators", label: "Educators (AEA pathway)", goal: 15, owner: "AEA Program" },
    { id: "faith", label: "Faith leaders", goal: 15, owner: "Coalition & Endorsements" },
    { id: "clerks", label: "County clerks", goal: 10, owner: "County Completion Routing" },
    { id: "current-officials", label: "Current elected officials", goal: 10, owner: "Coalition & Endorsements" },
    { id: "former-officials", label: "Former elected officials", goal: 15, owner: "Coalition & Endorsements" },
  ];
  const totalGoal = categories.reduce((s, c) => s + c.goal, 0);

  return {
    generatedAt: new Date().toISOString(),
    campaignGoal: "100 meaningful coalition conversations by Labor Day",
    deadline: LABOR_DAY,
    totalGoal,
    currentTotal: 0,
    trackConversationsNotEndorsements: true,
    categories: categories.map((c) => ({ ...c, current: 0 })),
  };
}


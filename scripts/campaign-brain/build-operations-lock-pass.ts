function main() {
  ensureDir(OPS_OUT);
  ensureDir(PACKETS_OUT);
  ensureDir(SHERWOOD_OUT);

  const generatedAt = new Date().toISOString();

  const ownershipSource = readJson<{
    mode?: string;
    calendarFlexPct?: string;
    coverageStandard?: Record<string, unknown>;
    assignments: OwnershipRow[];
  }>(path.join(OPS_DATA, "ownership-registry.source.json"));

  const endorsementSource = readJson<{ weekOneTargets: EndorsementTarget[] }>(
    path.join(OPS_DATA, "endorsement-strike-targets.source.json"),
  );

  const twentyWeek = readJson<{ weeks: WeekPlan[] }>(TWENTY_WEEK);
  const peoplePower = readJson<{ volunteerLeadership?: { foundingTeamGoal?: number; foundingTeamCurrent?: number; launchCall?: { date: string; time: string } } }>(
    path.join(BRAIN_DATA, "people-power-network.json"),
  );
  const sherwood = readJson<Record<string, unknown>>(path.join(BRAIN_DATA, "win-sherwood-operation.json")) ?? {};
  const coalition = readJson<{ sherwood?: Record<string, unknown> }>(path.join(BRAIN_DATA, "coalition-power-map-summary.json")) ?? {};

  const assignments = ownershipSource?.assignments ?? [];
  const weekOneTargets = endorsementSource?.weekOneTargets ?? [];
  const weeks30Day = (twentyWeek?.weeks ?? []).filter((w) => w.weekNumber >= 1 && w.weekNumber <= 4);

  const registry = {
    generatedAt,
    mode: "campaign_operations",
    disclaimer: DISCLAIMER,
    calendarFlexPct: ownershipSource?.calendarFlexPct ?? "15-20",
    coverageStandard: ownershipSource?.coverageStandard,
    unassignedCount: assignments.filter((a) => {
      const o = a.owner.trim().toLowerCase();
      return !o || o === "unassigned" || o === "tbd" || o.startsWith("tbd");
    }).length,
    assignments,
  };

  writeFileSync(path.join(OPS_OUT, "ownership-registry.json"), JSON.stringify(registry, null, 2));
  writeFileSync(path.join(OPS_OUT, "ownership-dashboard.md"), buildOwnershipDashboard(assignments, generatedAt));
  writeFileSync(path.join(OPS_OUT, "perfect-week-doctrine.md"), buildPerfectWeekDoctrine());

  for (const week of weeks30Day) {
    const dir = path.join(PACKETS_OUT, padWeek(week.weekNumber));
    ensureDir(dir);
    const pp = peoplePower?.volunteerLeadership ?? {};
    writeFileSync(path.join(dir, "candidate-packet.md"), buildCandidatePacket(week));
    writeFileSync(path.join(dir, "volunteer-packet.md"), buildVolunteerPacket(week, pp));
    writeFileSync(path.join(dir, "coalition-packet.md"), buildCoalitionPacket(week));
    writeFileSync(path.join(dir, "endorsement-packet.md"), buildEndorsementPacket(week, weekOneTargets));
    writeFileSync(path.join(dir, "social-media-packet.md"), buildSocialMediaPacket(week));
  }

  const sherwoodCmd = buildSherwoodCommandCenter(sherwood, coalition.sherwood ?? {});
  writeFileSync(path.join(SHERWOOD_OUT, "command-center.json"), JSON.stringify(sherwoodCmd, null, 2));
  writeFileSync(path.join(SHERWOOD_OUT, "command-center.md"), buildSherwoodMd(sherwoodCmd));
  writeFileSync(
    path.join(SHERWOOD_OUT, "checklist.md"),
    `# Sherwood Daily Checklist

- [ ] VIP table sales call block (owner: Sherwood Event lead)
- [ ] Sponsor outreach (1 contact minimum)
- [ ] Mobilize RSVP check
- [ ] Volunteer shift coverage confirmed
- [ ] Candidate invitation follow-ups
- [ ] Labor + NAACP invitation status
- [ ] Media advisory / pickup tracking
- [ ] Compliance items advancing (permits · security · alcohol review)

**Target before July 3:** ${sherwoodCmd.metrics.vipTablesGoal} VIP tables · 50 volunteers · 300 Mobilize RSVPs
`,
  );

  const strikeTeam = {
    generatedAt,
    weekOneTargets,
    rules: [
      "Log every ask: date · owner · status · next action",
      "Endorsement opportunities override bonus-tier county completion",
      "15-20% calendar flex reserved for coalition opportunities",
    ],
  };
  writeFileSync(path.join(OPS_OUT, "endorsement-strike-team.json"), JSON.stringify(strikeTeam, null, 2));
  writeFileSync(
    path.join(OPS_OUT, "endorsement-strike-team.md"),
    `# Endorsement Strike Team — Week One

| Organization | Owner | Ask date | Status | Next action |
|--------------|-------|----------|--------|-------------|
${weekOneTargets.map((t) => `| ${t.organization} | ${t.owner} | ${t.askDate} | ${t.status} | ${t.nextAction} |`).join("\n")}
`,
  );

  const coalitionSprint = buildCoalitionSprint();
  writeFileSync(path.join(OPS_OUT, "coalition-contact-sprint.json"), JSON.stringify(coalitionSprint, null, 2));
  writeFileSync(path.join(OPS_OUT, "coalition-contact-sprint.md"), buildCoalitionSprintMd(coalitionSprint));

  const motion = buildMotionSchedule();
  writeFileSync(path.join(OPS_OUT, "motion-production-schedule.json"), JSON.stringify(motion, null, 2));
  writeFileSync(path.join(OPS_OUT, "motion-production-schedule.md"), buildMotionScheduleMd(motion));

  writeFileSync(
    path.join(OPS_OUT, "operations-lock-pass.summary.json"),
    JSON.stringify(
      {
        generatedAt,
        disclaimer: DISCLAIMER,
        mode: "campaign_operations",
        ownershipFunctions: assignments.length,
        unassignedOwners: registry.unassignedCount,
        weeklyPacketWeeks: weeks30Day.length,
        sherwoodCommandCenter: true,
        endorsementWeekOneTargets: weekOneTargets.length,
        coalitionSprintGoal: coalitionSprint.totalGoal,
        coalitionSprintDeadline: LABOR_DAY,
        motionPerStopDeliverables: motion.perStopDeliverables.length,
      },
      null,
      2,
    ),
  );

  writeFileSync(
    path.join(OPS_OUT, "CAMPAIGN-OPERATIONS-MODE.md"),
    `# Campaign Operations Mode

> ${DISCLAIMER}

The project has crossed from planning into **leadership decision-making and field execution**.

The biggest risk is no longer the calendar — it is that a statewide operating system exists and **nobody owns enough pieces of it**.

## Start here

| Document | Purpose |
|----------|---------|
| [Ownership dashboard](./ownership-dashboard.md) | **Assign names before lunch** |
| [Perfect week doctrine](./perfect-week-doctrine.md) | What a perfect week looks like |
| [Weekly packets](./weekly-packets/week-01/candidate-packet.md) | Week 1 candidate · volunteer · coalition · endorsement · social |
| [Sherwood command center](./sherwood-60/command-center.md) | GOTV kickoff tracking |
| [Endorsement strike team](./endorsement-strike-team.md) | Week One targets |
| [Coalition contact sprint](./coalition-contact-sprint.md) | 100 conversations by Labor Day |
| [Motion production schedule](./motion-production-schedule.md) | 5 assets per stop |

## 30-day command structure

Weekly packets generated for weeks **1–4** (${weeks30Day.map((w) => w.range).join(" · ")}).

## Rebuild

\`\`\`bash
npm run campaign-brain:operations-lock:build
\`\`\`

Edit owners in \`data/campaign-brain/operations/ownership-registry.source.json\`.

## Not included (by design)

- Google Calendar write
- /events publish
- New election-plan dashboard sections
- Calendar operational lock (requires Phase C sign-off first)
`,
  );

  console.log(
    `Operations Lock Pass: ${assignments.length} functions · ${registry.unassignedCount} unassigned · ${weeks30Day.length} weekly packet sets · Sherwood command center ready`,
  );
}

main();

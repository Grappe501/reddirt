const PL = `[PLACEHOLDER — replace with approved copy — no unsourced claims]`;

function skeleton(intro: string, sections: string[]): string {
  return [intro, "", ...sections.map((s, i) => `---\n${i + 1}. ${s}\n`), "", `Sign-off / name\n${PL}`].join("\n");
}


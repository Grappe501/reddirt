export function mapTemplateRiskToCampaignVoice(risk: TemplateRiskDisplay): MessageStudioCampaignVoiceSettings["riskLevel"] {
  if (risk === "low") return "low";
  if (risk === "high") return "elevated";
  return "standard";
}

